#!/usr/bin/env python3
"""Procedural low-poly meshes (OBJ) and sand textures (PNG) for the beach.

    python3 sim/common/make_assets.py

Writes sim/common/meshes/*.obj and sim/common/textures/*.png. Deterministic,
numpy + Pillow only. Mesh frames follow sim/common/objects.yaml: origin at the
footprint centre on the ground, x along the long axis, z up, metres.
"""

import math
from pathlib import Path

import numpy as np
from PIL import Image

HERE = Path(__file__).resolve().parent
MESH_DIR = HERE / 'meshes'
TEX_DIR = HERE / 'textures'


class Mesh:
    """Triangle soup made of closed parts; normals point away from each part's centre."""

    def __init__(self):
        self.parts = []   # (vertices (n,3), faces (m,3), smooth)

    def add(self, verts, faces, smooth=True):
        v = np.asarray(verts, dtype=float)
        f = np.asarray(faces, dtype=int)
        # Orient every face outward relative to the part centroid.
        c = v.mean(axis=0)
        for k, (a, b, d) in enumerate(f):
            n = np.cross(v[b] - v[a], v[d] - v[a])
            if np.dot(n, (v[a] + v[b] + v[d]) / 3.0 - c) < 0:
                f[k] = (a, d, b)
        self.parts.append((v, f, smooth))
        return self

    def write_obj(self, path, comment):
        lines = [f'# {comment}', '# generated by sim/common/make_assets.py']
        vbase = nbase = 1
        for v, f, smooth in self.parts:
            fn = np.cross(v[f[:, 1]] - v[f[:, 0]], v[f[:, 2]] - v[f[:, 0]])
            fn /= np.linalg.norm(fn, axis=1, keepdims=True) + 1e-12
            for p in v:
                lines.append(f'v {p[0]:.5f} {p[1]:.5f} {p[2]:.5f}')
            if smooth:
                vn = np.zeros_like(v)
                for k in range(3):
                    np.add.at(vn, f[:, k], fn)
                vn /= np.linalg.norm(vn, axis=1, keepdims=True) + 1e-12
                for n in vn:
                    lines.append(f'vn {n[0]:.4f} {n[1]:.4f} {n[2]:.4f}')
                for a, b, d in f:
                    lines.append(f'f {a + vbase}//{a + nbase} {b + vbase}//{b + nbase} {d + vbase}//{d + nbase}')
                nbase += len(vn)
            else:
                for n in fn:
                    lines.append(f'vn {n[0]:.4f} {n[1]:.4f} {n[2]:.4f}')
                for k, (a, b, d) in enumerate(f):
                    lines.append(f'f {a + vbase}//{k + nbase} {b + vbase}//{k + nbase} {d + vbase}//{k + nbase}')
                nbase += len(fn)
            vbase += len(v)
        Path(path).write_text('\n'.join(lines) + '\n')


def box(m, size, center=(0, 0, 0), yaw=0.0):
    sx, sy, sz = (s / 2.0 for s in size)
    corners = np.array([[x, y, z] for z in (-sz, sz) for y in (-sy, sy) for x in (-sx, sx)])
    c, s = math.cos(yaw), math.sin(yaw)
    corners = corners @ np.array([[c, s, 0], [-s, c, 0], [0, 0, 1]]) + np.asarray(center)
    quads = [(0, 1, 3, 2), (4, 6, 7, 5), (0, 4, 5, 1), (2, 3, 7, 6), (0, 2, 6, 4), (1, 5, 7, 3)]
    faces = [t for a, b, cc, d in quads for t in ((a, b, cc), (a, cc, d))]
    return m.add(corners, faces, smooth=False)


def lathe(m, profile, axis='x', segments=16, offset=(0, 0, 0), smooth=True):
    """Surface of revolution. profile: [(s, r)] along the axis; ends are capped."""
    verts, faces = [], []
    for s, r in profile:
        for k in range(segments):
            a = 2 * math.pi * k / segments
            u, w = r * math.cos(a), r * math.sin(a)
            verts.append((s, u, w) if axis == 'x' else (u, w, s))
    n = len(profile)
    for i in range(n - 1):
        for k in range(segments):
            a, b = i * segments + k, i * segments + (k + 1) % segments
            c, d = a + segments, b + segments
            faces += [(a, b, d), (a, d, c)]
    for i, s in ((0, profile[0][0]), (n - 1, profile[-1][0])):
        verts.append((s, 0, 0) if axis == 'x' else (0, 0, s))
        ctr = len(verts) - 1
        for k in range(segments):
            faces.append((ctr, i * segments + k, i * segments + (k + 1) % segments))
    verts = np.asarray(verts) + np.asarray(offset)
    return m.add(verts, faces, smooth=smooth)


def lying(profile, segments=16):
    """A bottle/can profile lying along x, resting on its widest radius, centred."""
    s0, s1 = profile[0][0], profile[-1][0]
    rmax = max(r for _, r in profile)
    prof = [(s - (s0 + s1) / 2.0, r) for s, r in profile]
    return lathe(Mesh(), prof, axis='x', segments=segments, offset=(0, 0, rmax))


def blob(m, radii, center, seed, bumps=0.15, rings=8, segments=12, flat_bottom=True):
    """Noisy ellipsoid (rocks, shells)."""
    rng = np.random.default_rng(seed)
    verts, faces = [], []
    noise = 1.0 + bumps * (rng.random((rings + 1, segments)) - 0.5)
    for i in range(rings + 1):
        th = math.pi * i / rings
        for k in range(segments):
            ph = 2 * math.pi * k / segments
            r = noise[i, k] if 0 < i < rings else 1.0
            verts.append((radii[0] * r * math.sin(th) * math.cos(ph),
                          radii[1] * r * math.sin(th) * math.sin(ph),
                          radii[2] * r * math.cos(th)))
    for i in range(rings):
        for k in range(segments):
            a, b = i * segments + k, i * segments + (k + 1) % segments
            faces += [(a, b, b + segments), (a, b + segments, a + segments)]
    v = np.asarray(verts)
    if flat_bottom:
        v[:, 2] = np.maximum(v[:, 2], -0.3 * radii[2])
    v[:, 2] -= v[:, 2].min()
    return m.add(v + np.asarray(center), faces)


def make_meshes():
    meshes = {}
    meshes['pet_bottle_500'] = lying([(0, 0.0), (0.005, 0.03), (0.13, 0.0325), (0.17, 0.031),
                                      (0.19, 0.016), (0.20, 0.0135), (0.21, 0.0135)])
    meshes['can_330'] = lying([(0, 0.0), (0.004, 0.026), (0.008, 0.033), (0.105, 0.033),
                               (0.112, 0.027), (0.115, 0.027)])
    meshes['food_tin'] = lying([(0, 0.0), (0.002, 0.0375), (0.108, 0.0375), (0.11, 0.0)])
    meshes['glass_bottle_330'] = lying([(0, 0.0), (0.004, 0.028), (0.14, 0.03), (0.17, 0.022),
                                        (0.20, 0.013), (0.23, 0.013)])
    meshes['glass_jar'] = lathe(Mesh(), [(0, 0.0), (0.002, 0.0335), (0.055, 0.0335), (0.06, 0.029),
                                         (0.07, 0.029), (0.07, 0.0)], axis='z')
    meshes['poly_cup'] = lathe(Mesh(), [(0, 0.0), (0.001, 0.023), (0.059, 0.031), (0.06, 0.0)], axis='z')
    meshes['cigarette_pack'] = box(Mesh(), (0.088, 0.055, 0.022), (0, 0, 0.011))
    m = Mesh()
    box(m, (0.18, 0.12, 0.004), (0, 0, 0.002))          # tray floor and walls (open top)
    for sgn in (-1, 1):
        box(m, (0.18, 0.004, 0.05), (0, sgn * 0.058, 0.025))
        box(m, (0.004, 0.12, 0.05), (sgn * 0.088, 0, 0.025))
    meshes['food_container'] = m

    shell = Mesh()
    blob(shell, (0.03, 0.025, 0.012), (0, 0, 0), seed=1, bumps=0.25, segments=16)
    meshes['shell'] = shell
    meshes['rock_small'] = blob(Mesh(), (0.06, 0.045, 0.04), (0, 0, 0), seed=2)
    meshes['rock_medium'] = blob(Mesh(), (0.12, 0.09, 0.08), (0, 0, 0), seed=3)
    weed = Mesh()
    for j, y0 in enumerate((-0.06, 0.0, 0.06)):        # three wavy strips
        for i in range(8):
            x = -0.2 + 0.05 * i + 0.025
            y = y0 + 0.02 * math.sin(3.0 * x * 10 + j)
            box(weed, (0.052, 0.035, 0.006), (x, y, 0.003 + 0.004 * (j % 2)), yaw=0.4 * math.cos(x * 20 + j))
    meshes['seaweed'] = weed
    meshes['driftwood'] = lying([(0, 0.0), (0.02, 0.025), (0.2, 0.04), (0.45, 0.035), (0.7, 0.04),
                                 (0.88, 0.028), (0.9, 0.0)], segments=8)

    b = Mesh()
    box(b, (0.60, 0.45, 0.02), (0, 0, 0.01))
    for sgn in (-1, 1):
        box(b, (0.60, 0.02, 0.50), (0, sgn * 0.215, 0.25))
        box(b, (0.02, 0.41, 0.50), (sgn * 0.29, 0, 0.25))
    meshes['bin'] = b

    t = Mesh()
    for sx in (-1, 1):
        for sy in (-1, 1):
            box(t, (0.12, 0.12, 1.8), (0.9 * sx, 0.9 * sy, 0.9))
    box(t, (2.0, 2.0, 0.1), (0, 0, 1.85))                 # floor
    box(t, (2.0, 0.05, 1.0), (0, -0.975, 2.4))            # back wall
    for sx in (-1, 1):
        box(t, (0.05, 2.0, 1.0), (sx * 0.975, 0, 2.4))    # side walls
    box(t, (2.0, 0.05, 0.45), (0, 0.975, 2.125))          # front parapet
    box(t, (2.4, 2.4, 0.08), (0, 0, 2.95))                # roof
    for sx in (-1, 1):                                     # ladder in front
        box(t, (0.05, 0.05, 2.2), (sx * 0.25, 1.6, 0.95))
    for k in range(6):
        box(t, (0.5, 0.04, 0.04), (0, 1.6 - 0.0, 0.3 + 0.3 * k))
    meshes['lifeguard_tower'] = t
    meshes['fence_post'] = lathe(Mesh(), [(0, 0.0), (0.001, 0.05), (0.97, 0.05), (1.0, 0.03), (1.0, 0.0)],
                                 axis='z', segments=8)
    return meshes


def make_textures(n=512):
    """Sand albedo with wind ripples, its normal map, and a darker wet-sand albedo."""
    rng = np.random.default_rng(0)
    y, x = np.mgrid[0:n, 0:n] / n
    # Wind ripples: wavy stripes, tileable (integer frequencies over the tile).
    ripples = np.sin(2 * math.pi * (12 * y + 0.6 * np.sin(2 * math.pi * 2 * x)))
    grain = rng.random((n, n))
    h = 0.5 + 0.35 * ripples + 0.15 * grain
    base = np.array([0.86, 0.76, 0.58])
    shade = 0.85 + 0.15 * (0.6 * (ripples + 1) / 2 + 0.4 * grain)
    albedo = np.clip(base[None, None, :] * shade[..., None], 0, 1)
    Image.fromarray((albedo * 255).astype(np.uint8), 'RGB').save(TEX_DIR / 'sand_albedo.png')
    wet = np.clip(np.array([0.72, 0.62, 0.47])[None, None, :] * (0.9 + 0.1 * grain[..., None]), 0, 1)
    Image.fromarray((wet * 255).astype(np.uint8), 'RGB').save(TEX_DIR / 'wet_sand_albedo.png')
    gy, gx = np.gradient(h)
    nrm = np.dstack([-gx * 4, -gy * 4, np.ones_like(h)])
    nrm /= np.linalg.norm(nrm, axis=2, keepdims=True)
    Image.fromarray(((nrm * 0.5 + 0.5) * 255).astype(np.uint8), 'RGB').save(TEX_DIR / 'sand_normal.png')


def main():
    MESH_DIR.mkdir(exist_ok=True)
    TEX_DIR.mkdir(exist_ok=True)
    for name, mesh in make_meshes().items():
        mesh.write_obj(MESH_DIR / f'{name}.obj', name)
    make_textures()
    print(f'wrote meshes to {MESH_DIR} and textures to {TEX_DIR}')


if __name__ == '__main__':
    main()
