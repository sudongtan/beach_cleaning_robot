#!/usr/bin/env python3
"""Realistic trash visuals (B5): UV-mapped meshes + one texture atlas per item.

    python3 sim/common/trash_visuals.py        (also run by make_assets.py)

Writes sim/common/meshes/<item>_print.obj (the opaque, textured parts: labels, caps, lids, prints)
and, for see-through items, <item>_body.obj (the plain transparent body), and
sim/common/textures/<item>.png. objects.yaml `visuals` lists them per item; sizes, masses and
collisions there don't change (visuals only: the mesh bounding boxes match the collision boxes,
sim/common/tests/test_trash_visuals.py). Labels are invented and brand-free. Deterministic: numpy +
Pillow; text uses DejaVu Sans when installed, else Pillow's default font.

Mesh frame as objects.yaml: origin at the footprint centre on the ground, x along the long axis, z up.
"""

import math
from pathlib import Path

import numpy as np
from PIL import Image, ImageDraw, ImageFilter, ImageFont

HERE = Path(__file__).resolve().parent
MESH_DIR = HERE / 'meshes'
TEX_DIR = HERE / 'textures'
TEX = 512                              # atlas size (px), square
SEG = 32                               # segments around round items (A1: 16)
FONT = Path('/usr/share/fonts/truetype/dejavu/DejaVuSans-Bold.ttf')


def font(size):
    try:
        return ImageFont.truetype(str(FONT), size)
    except OSError:
        return ImageFont.load_default()


class UvMesh:
    """Parts with per-vertex UVs; normals smooth per part (or flat), outward (or inward)."""

    def __init__(self):
        self.parts = []                # (v (n,3), uv (n,2), f (m,3), smooth)

    def add(self, v, uv, f, smooth=True, inward=False):
        v, uv, f = np.asarray(v, float), np.asarray(uv, float), np.asarray(f, int)
        c = v.mean(axis=0)
        for k, (a, b, d) in enumerate(f):
            n = np.cross(v[b] - v[a], v[d] - v[a])
            out = np.dot(n, (v[a] + v[b] + v[d]) / 3.0 - c) > 0
            if out == inward:
                f[k] = (a, d, b)
        self.parts.append((v, uv, f, smooth))
        return self

    def bounds(self):
        allv = np.vstack([p[0] for p in self.parts])
        return allv.min(axis=0), allv.max(axis=0)

    def triangles(self):
        return sum(len(p[2]) for p in self.parts)

    def write_obj(self, path, comment):
        lines = [f'# {comment}', '# generated by sim/common/trash_visuals.py (B5)']
        base = 1
        for v, uv, f, smooth in self.parts:
            fn = np.cross(v[f[:, 1]] - v[f[:, 0]], v[f[:, 2]] - v[f[:, 0]])
            fn /= np.linalg.norm(fn, axis=1, keepdims=True) + 1e-12
            vn = np.zeros_like(v)
            if smooth:
                for k in range(3):
                    np.add.at(vn, f[:, k], fn)
            else:
                vn[f.reshape(-1)] = np.repeat(fn, 3, axis=0)
            vn /= np.linalg.norm(vn, axis=1, keepdims=True) + 1e-12
            lines += [f'v {p[0]:.5f} {p[1]:.5f} {p[2]:.5f}' for p in v]
            lines += [f'vt {t[0]:.4f} {t[1]:.4f}' for t in uv]
            lines += [f'vn {n[0]:.4f} {n[1]:.4f} {n[2]:.4f}' for n in vn]
            lines += ['f ' + ' '.join(f'{i + base}/{i + base}/{i + base}' for i in tri) for tri in f]
            base += len(v)
        Path(path).write_text('\n'.join(lines) + '\n')


def region(px):
    """Atlas region in pixels (left, top, right, bottom) -> UV (u0, v0, u1, v1), v up."""
    l, t, r, b = px
    return l / TEX, 1 - b / TEX, r / TEX, 1 - t / TEX


def lathe(m, profile, reg, axis='x', offset=(0, 0, 0), caps=(True, True), inward=False, segments=SEG):
    """Surface of revolution [(s, r)] with UVs: around -> u, along the profile -> v inside reg (pixels).
    Capped ends get a disc mapping in the same region's lower / upper edge row."""
    u0, v0, u1, v1 = region(reg)
    s_min, s_max = profile[0][0], profile[-1][0]
    span = (s_max - s_min) or 1.0
    verts, uvs, faces = [], [], []

    def point(s, r, a):
        y, z = r * math.cos(a), r * math.sin(a)
        return (s, y, z) if axis == 'x' else (y, z, s)

    for s, r in profile:
        for k in range(segments + 1):                     # seam vertex duplicated for the texture wrap
            a = 2 * math.pi * k / segments
            verts.append(point(s, r, a))
            uvs.append((u0 + (u1 - u0) * k / segments, v0 + (v1 - v0) * (s - s_min) / span))
    ring = segments + 1
    for i in range(len(profile) - 1):
        for k in range(segments):
            a, b = i * ring + k, i * ring + k + 1
            faces += [(a, b, b + ring), (a, b + ring, a + ring)]
    for end, (s, _) in ((0, profile[0]), (len(profile) - 1, profile[-1])):
        if not caps[0 if end == 0 else 1]:
            continue
        verts.append(point(s, 0.0, 0.0))
        uvs.append((u0 + 0.5 * (u1 - u0), v0 if end == 0 else v1))
        ctr = len(verts) - 1
        for k in range(segments):
            faces.append((ctr, end * ring + k, end * ring + k + 1))
    v = np.asarray(verts) + np.asarray(offset)
    return m.add(v, uvs, faces, smooth=True, inward=inward)


def box(m, size, center, reg):
    """Box with 4 vertices per face (flat), every face mapped to the whole region."""
    sx, sy, sz = (s / 2 for s in size)
    cx, cy, cz = center
    u0, v0, u1, v1 = region(reg)
    quads = [((-sx, -sy, sz), (sx, -sy, sz), (sx, sy, sz), (-sx, sy, sz)),        # top
             ((-sx, -sy, -sz), (-sx, sy, -sz), (sx, sy, -sz), (sx, -sy, -sz)),     # bottom
             ((-sx, -sy, -sz), (sx, -sy, -sz), (sx, -sy, sz), (-sx, -sy, sz)),     # -y
             ((sx, sy, -sz), (-sx, sy, -sz), (-sx, sy, sz), (sx, sy, sz)),         # +y
             ((sx, -sy, -sz), (sx, sy, -sz), (sx, sy, sz), (sx, -sy, sz)),         # +x
             ((-sx, sy, -sz), (-sx, -sy, -sz), (-sx, -sy, sz), (-sx, sy, sz))]     # -x
    verts, uvs, faces = [], [], []
    for q in quads:
        n = len(verts)
        verts += [(x + cx, y + cy, z + cz) for x, y, z in q]
        uvs += [(u0, v0), (u1, v0), (u1, v1), (u0, v1)]
        faces += [(n, n + 1, n + 2), (n, n + 2, n + 3)]
    return m.add(verts, uvs, faces, smooth=False)


def box_faces(m, size, center, regs):
    """Box whose faces map to their own regions: regs = {'top', 'bottom', 'front' (-y), 'back' (+y),
    'end' (+-x)} in pixels (cigarette pack)."""
    sx, sy, sz = (s / 2 for s in size)
    cx, cy, cz = center
    quads = {'top': ((-sx, -sy, sz), (sx, -sy, sz), (sx, sy, sz), (-sx, sy, sz)),
             'bottom': ((-sx, sy, -sz), (sx, sy, -sz), (sx, -sy, -sz), (-sx, -sy, -sz)),
             'front': ((-sx, -sy, -sz), (sx, -sy, -sz), (sx, -sy, sz), (-sx, -sy, sz)),
             'back': ((sx, sy, -sz), (-sx, sy, -sz), (-sx, sy, sz), (sx, sy, sz)),
             'end+': ((sx, -sy, -sz), (sx, sy, -sz), (sx, sy, sz), (sx, -sy, sz)),
             'end-': ((-sx, sy, -sz), (-sx, -sy, -sz), (-sx, -sy, sz), (-sx, sy, sz))}
    for name, q in quads.items():
        u0, v0, u1, v1 = region(regs[name.rstrip('+-')])
        m.add([(x + cx, y + cy, z + cz) for x, y, z in q], [(u0, v0), (u1, v0), (u1, v1), (u0, v1)],
              [(0, 1, 2), (0, 2, 3)], smooth=False)
    return m


def lying(profile):
    """Profile along x, centred, resting on its widest radius: (shifted profile, z offset)."""
    s0, s1 = profile[0][0], profile[-1][0]
    return [(s - (s0 + s1) / 2, r) for s, r in profile], max(r for _, r in profile)


def section(profile, a, b, grow=0.0):
    """The part of a profile between s = a and b (linear interpolation at the ends), radius + grow."""
    def r_at(s):
        for (s0, r0), (s1, r1) in zip(profile, profile[1:]):
            if s0 <= s <= s1:
                return r0 + (r1 - r0) * ((s - s0) / (s1 - s0) if s1 > s0 else 0)
        return profile[-1][1]
    pts = [(a, r_at(a))] + [(s, r) for s, r in profile if a < s < b] + [(b, r_at(b))]
    return [(s, r + grow) for s, r in pts]


# --- textures ---------------------------------------------------------------------------------

def canvas(color):
    return Image.new('RGB', (TEX, TEX), tuple(int(c * 255) for c in color))


def grime(img, seed, amount=0.10):
    """Faint wear: sand-coloured specks and soft blotches (sun, sand, handling)."""
    rng = np.random.default_rng(seed)
    a = np.asarray(img, dtype=float) / 255
    blot = Image.fromarray((rng.random((TEX // 16, TEX // 16)) * 255).astype(np.uint8)).resize(
        (TEX, TEX), Image.BILINEAR).filter(ImageFilter.GaussianBlur(6))
    b = np.asarray(blot, dtype=float)[..., None] / 255
    sand = np.array([0.80, 0.70, 0.52])
    a = a * (1 - amount * b) + sand * amount * b
    specks = rng.random((TEX, TEX)) < 0.004
    a[specks] = sand
    return Image.fromarray((np.clip(a, 0, 1) * 255).astype(np.uint8))


def fitted(text, width, height):
    """The largest font (up to height px) whose text fits width px."""
    size = max(8, int(height))
    while size > 8:
        f = font(size)
        if ImageDraw.Draw(Image.new('RGB', (1, 1))).textlength(text, font=f) <= width:
            return f
        size -= 2
    return font(8)


def label_band(img, box_px, bg, fg, text, sub='', stripe=None):
    """A printed label in box_px: background, a stripe, the brand text twice around (it wraps)."""
    d = ImageDraw.Draw(img)
    l, t, r, b = box_px
    d.rectangle(box_px, fill=bg)
    h, w = b - t, r - l
    if stripe:
        d.rectangle((l, t + int(0.70 * h), r, t + int(0.82 * h)), fill=stripe)
    big, small = fitted(text, 0.42 * w, 0.30 * h), fitted(sub, 0.42 * w, 0.10 * h) if sub else None
    for k in range(2):                                   # twice around: readable from any side
        x = l + k * w // 2 + w // 25
        d.text((x, t + int(0.22 * h)), text, fill=fg, font=big)
        if sub:
            d.text((x, t + int(0.56 * h)), sub, fill=fg, font=small)


