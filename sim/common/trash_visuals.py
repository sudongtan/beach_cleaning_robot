def food_container():
    """Open takeaway tray (expanded polystyrene, food-soiled)."""
    m = UvMesh()
    box(m, (0.18, 0.12, 0.004), (0, 0, 0.002), CAP)
    for sgn in (-1, 1):
        box(m, (0.18, 0.004, 0.05), (0, sgn * 0.058, 0.025), LABEL)
        box(m, (0.004, 0.12, 0.05), (sgn * 0.088, 0, 0.025), LABEL)
    img = canvas((0.95, 0.95, 0.92))
    d = ImageDraw.Draw(img)
    d.rectangle(LABEL, fill=(240, 240, 235))
    d.rectangle(CAP, fill=(238, 236, 228))
    rng = np.random.default_rng(8)
    for _ in range(9):                                                       # sauce and grease stains
        x, y, r = rng.integers(10, 246), rng.integers(266, 500), rng.integers(10, 40)
        d.ellipse((x - r, y - r, x + r, y + r), fill=(170, 90, 40) if rng.random() < 0.6 else (210, 180, 120))
    return {'print': m, 'texture': grime(img.filter(ImageFilter.GaussianBlur(1)), 8, 0.10)}


ITEMS = {'pet_bottle_500': pet_bottle_500, 'can_330': can_330, 'food_tin': food_tin,
         'glass_bottle_330': glass_bottle_330, 'glass_jar': glass_jar, 'poly_cup': poly_cup,
         'cigarette_pack': cigarette_pack, 'food_container': food_container}


def build():
    """{item: {'print': UvMesh, 'body': UvMesh (see-through items only), 'texture': Image}}."""
    return {name: f() for name, f in ITEMS.items()}


def main():
    MESH_DIR.mkdir(exist_ok=True)
    TEX_DIR.mkdir(exist_ok=True)
    for name, parts in build().items():
        parts['print'].write_obj(MESH_DIR / f'{name}_print.obj', f'{name}: printed / opaque parts')
        if 'body' in parts:
            parts['body'].write_obj(MESH_DIR / f'{name}_body.obj', f'{name}: transparent body')
        parts['texture'].save(TEX_DIR / f'{name}.png')
    print(f'wrote trash visuals to {MESH_DIR} and {TEX_DIR}')


if __name__ == '__main__':
    main()
