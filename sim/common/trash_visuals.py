# Atlas layout (pixels): rows of regions, each item uses what it needs.
LABEL = (0, 0, 512, 256)               # wrap-around label / main print
CAP = (0, 256, 256, 512)               # cap, lid, rim
END = (256, 256, 512, 512)             # can / tin ends, other parts


def pet_bottle_500():
    prof = [(0, 0.0), (0.005, 0.03), (0.13, 0.0325), (0.17, 0.031), (0.19, 0.016), (0.20, 0.0135), (0.21, 0.0135)]
    p, rz = lying(prof)
    body = lathe(UvMesh(), p, (0, 0, 8, 8), offset=(0, 0, rz))
    printed = UvMesh()
    lathe(printed, section(p, -0.06, 0.02, grow=0.0005), LABEL, offset=(0, 0, rz), caps=(False, False))
    lathe(printed, [(0.088, 0.0145), (0.105, 0.0145), (0.105, 0.0)], CAP, offset=(0, 0, rz), caps=(True, False))
    img = canvas((0.85, 0.92, 0.97))
    label_band(img, LABEL, (20, 90, 170), (250, 250, 250), 'CLEARSPRING', 'natural mineral water 500 ml',
               stripe=(120, 200, 240))
    ImageDraw.Draw(img).rectangle(CAP, fill=(30, 120, 210))
    return {'body': body, 'print': printed, 'texture': grime(img, 1, 0.06)}


