#!/usr/bin/env python3
"""A test stage for D0b / D0c: a scene + the robot + (for picks) the items + view cameras.

    python sim/isaac/compose.py --scene flat|<seed> --robot ROBOT.usd --out OUT.usda [--pick]

The scene stays a separate, robot-free file (sim/isaac/load_scene.py); this writes a small layer
that sublayers it and references the imported robot at `robot_start`, standing (its base_link at the
Gazebo standing height above the terrain + a small clearance). It also sets the physics rate
(PhysxSceneAPI timeStepsPerSecond, Gazebo's controller rate) and deactivates any physics scene the
robot asset brings along. `flat` = seed 3 with slope / roughness / dunes 0, the laptop's
d0_from_laptop/c7/flat3.yaml (the Gazebo reference walk's flat scene).
"""

import argparse
import json
import math
import os
import sys
from pathlib import Path

import numpy as np
import yaml

HERE = Path(__file__).resolve().parent
REPO = HERE.parents[1]
sys.path.insert(0, str(HERE))
import kit_pxr  # noqa: E402

kit_pxr.ensure_pxr()
from pxr import Gf, Sdf, Usd, UsdGeom, UsdPhysics  # noqa: E402

import load_scene  # noqa: E402
import robot_model  # noqa: E402
from load_scene import ground_z, terrain_mod  # noqa: E402

ROBOT_PRIM = '/World/Robot'
PICK_ROOT = '/World/PickItems'
VIEW_ROOT = '/World/ViewCameras'


def scene_source(scene_arg, laptop):
    """(seed, scenes.yaml path, name) for `flat` or a seed number."""
    if str(scene_arg) == 'flat':
        return 3, laptop / 'c7' / 'flat3.yaml', 'flat3'
    s = int(scene_arg)
    return s, REPO / 'bench' / 'scenes.yaml', str(s)


def reference_walk(laptop, scene_arg):
    """The Gazebo reference (c7/<flat|seed3>/summary.yaml) for this scene, or None."""
    sub = {'flat': 'flat', '3': 'seed3'}.get(str(scene_arg))
    p = laptop / 'c7' / sub / 'summary.yaml' if sub else None
    if p and p.is_file():
        with open(p) as f:
            return yaml.safe_load(f)
    return None


def spawn_pose(scene, base_height, clearance):
    """base_link pose at robot_start: (x, y, z, yaw)."""
    x, y, yaw = map(float, scene['robot_start']['pose'])
    z = float(terrain_mod.height_at(scene['terrain'], x, y)) + base_height + clearance
    return x, y, z, yaw


def look_at(pos, target):
    """Gazebo-convention camera rotation (x forward, z up) looking from pos at target."""
    f = np.asarray(target, float) - np.asarray(pos, float)
    f /= np.linalg.norm(f)
    left = np.cross([0.0, 0.0, 1.0], f)
    left /= np.linalg.norm(left)
    up = np.cross(f, left)
    return np.column_stack([f, left, up])


def set_physics_rate(stage, hz):
    """PhysxSceneAPI timeStepsPerSecond on /World/PhysicsScene (Isaac 6.2's PhysxScene.set_dt
    writes the same attribute). Authored by name: usd-core has no PhysxSchema."""
    prim = stage.GetPrimAtPath('/World/PhysicsScene')
    prim.AddAppliedSchema('PhysxSceneAPI')
    prim.CreateAttribute('physxScene:timeStepsPerSecond', Sdf.ValueTypeNames.UInt).Set(int(hz))


def compose(scene_usda, robot_usd, out, spawn, physics_hz, pick_items=(), objects=None, view=None, terrain=None):
    out = Path(out)
    out.parent.mkdir(parents=True, exist_ok=True)
    if out.exists():
        out.unlink()
    # a stage on its real path, so the relative sublayer / reference resolve while composing
    # (in memory, the robot's own physics scene wasn't found and stayed active: a Mac test caught it)
    stage = Usd.Stage.CreateNew(str(out))
    layer = stage.GetRootLayer()
    layer.subLayerPaths.append(load_scene.rel_asset(scene_usda, out.parent))
    UsdGeom.SetStageMetersPerUnit(stage, 1.0)
    UsdGeom.SetStageUpAxis(stage, UsdGeom.Tokens.z)
    UsdPhysics.SetStageKilogramsPerUnit(stage, 1.0)
    stage.SetDefaultPrim(stage.GetPrimAtPath('/World'))
    layer.documentation = f'GENERATED by sim/isaac/compose.py: {Path(scene_usda).name} + robot. Do not edit.'
    # keep the scene's time-code range (D0 prep: without one the timeline clock stays at 0)
    src = Usd.Stage.Open(str(scene_usda))
    stage.SetTimeCodesPerSecond(src.GetTimeCodesPerSecond())
    stage.SetStartTimeCode(src.GetStartTimeCode())
    stage.SetEndTimeCode(src.GetEndTimeCode())

    set_physics_rate(stage, physics_hz)

    x, y, z, yaw = spawn
    robot = UsdGeom.Xform.Define(stage, ROBOT_PRIM)
    robot.GetPrim().GetReferences().AddReference(load_scene.rel_asset(robot_usd, out.parent))
    robot.ClearXformOpOrder()
    load_scene.set_pose(robot, (x, y, z), load_scene.yaw_quat(yaw))
    for p in Usd.PrimRange(robot.GetPrim()):            # one physics scene: the scene's
        if p.IsA(UsdPhysics.Scene):
            p.SetActive(False)

    if pick_items:
        looks = load_scene.Looks(stage, out.parent)
        meshes = load_scene.MeshCache()
        UsdGeom.Xform.Define(stage, PICK_ROOT)
        t = terrain
        for k, name in enumerate(pick_items):            # parked behind the robot until used
            spec = objects['trash'][name]
            px, py = x - 2.0 * math.cos(yaw) - 0.5 * k * math.sin(yaw), y - 2.0 * math.sin(yaw) + 0.5 * k * math.cos(yaw)
            pz = ground_z(t, px, py, spec['footprint_radius'], 'max') + load_scene.SPAWN_GAP if t else 0.05
            load_scene.object_prim(stage, looks, meshes, PICK_ROOT, name, spec, (px, py, 0.0), pz,
                                   spec['material'], objects['classes'][spec['material']], dynamic=True)

    if view:
        UsdGeom.Scope.Define(stage, VIEW_ROOT)
        for name, (offset, target_offset) in view.items():
            c, s = math.cos(yaw), math.sin(yaw)
            def w(o):
                return (x + c * o[0] - s * o[1], y + s * o[0] + c * o[1], z + o[2])
            p = w(offset)
            cam = load_scene.camera(stage, name, p, look_at(p, w(target_offset)), 1.2, (640, 480), (0.05, 100.0))
            # load_scene.camera writes under /World/Cameras; keep view cameras there too (render products)
    stage.GetRootLayer().Save()
    return out


VIEWS = {
    # name: (camera offset, look-at offset) in the robot's spawn frame (x forward, y left, z up)
    'walk': {'view_walk': ((-2.2, -2.6, 0.9), (1.0, 0.0, -0.1))},
    'pick': {'view_pick': ((0.9, -0.9, 0.5), (0.35, 0.0, -0.15))},
}


def build(scene_arg, robot_usd, out, pick=False, robot_cfg=None, laptop=None):
    robot_cfg = robot_cfg or robot_model.load_robot_cfg()
    laptop = laptop or robot_model.laptop_dir(robot_cfg)
    seed, scenes_path, name = scene_source(scene_arg, laptop)
    scene_usda = load_scene.OUT_DIR / f'scene_{name}.usda'
    load_scene.write_scene(seed, scene_usda, scenes_path)
    scene = load_scene.export_terrain.load_scene(seed, Path(scenes_path))
    ref = reference_walk(laptop, scene_arg) or reference_walk(laptop, 'flat')
    trunk_height = float(ref['standing']['trunk_above_ground_m']['mean'])
    urdf = robot_model.Urdf(laptop / robot_cfg['urdf_import']['urdf'])
    r = robot_cfg['robot']
    # Gazebo measures the trunk; the robot prim's origin is the URDF root (base_link)
    base_height = trunk_height - float(urdf.fixed_transform(r['root_link'], r['body_link'])[2, 3])
    spawn = spawn_pose(scene, base_height, float(robot_cfg['stand']['spawn_clearance_m']))
    objects, _, _ = load_scene.load_configs()
    items = []
    if pick:
        from pick import load_cases
        _, _, cases = load_cases(laptop / robot_cfg['pick']['plans'], robot_cfg['pick']['stance'])
        items = sorted({c['item'] for c in cases})
    out = compose(scene_usda, robot_usd, out, spawn, robot_cfg['policy']['physics_hz'], items, objects,
                  VIEWS['pick' if pick else 'walk'], terrain=scene['terrain'])
    meta = {'scene': str(scene_arg), 'seed': seed, 'scenes_yaml': str(scenes_path), 'scene_usda': str(scene_usda),
            'robot_usd': str(robot_usd), 'spawn_base_link': spawn, 'base_height_m': base_height,
            'trunk_height_ref_m': trunk_height, 'reference': ref,
            'pick_items': items, 'robot_prim': ROBOT_PRIM, 'pick_root': PICK_ROOT}
    Path(str(out) + '.json').write_text(json.dumps(meta, indent=2))
    return out, meta


def main():
    ap = argparse.ArgumentParser(description=__doc__.split('\n')[0])
    ap.add_argument('--scene', required=True, help='flat or a seed')
    ap.add_argument('--robot', required=True, help='imported robot USD')
    ap.add_argument('--out', required=True)
    ap.add_argument('--pick', action='store_true', help='add the pick items')
    a = ap.parse_args()
    out, meta = build(a.scene, a.robot, a.out, a.pick)
    print(out, json.dumps(meta['spawn_base_link']))
    kit_pxr.close(0)


if __name__ == '__main__':
    main()
